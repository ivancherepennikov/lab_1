"""Generate PRNGVectors.h for one algorithm from the reference model."""
import sys
from reference import sequence

STEPS = 10
CASES32 = {
    "fibonacci": [(1, 0), (0xACE1, 0xB400), (0xDEADBEEF, 0)],
    "galois": [(1, 0), (0xACE1, 0xB400), (0xDEADBEEF, 0)],
    "xorshift": [(1, 0), (2463534242, 0), (0xDEADBEEF, 0)],
}
CASES64 = {
    "fibonacci": [(1, 0), (0xACE1, 0xB400), (0xDEADBEEFCAFEBABE, 0)],
    "galois": [(1, 0), (0xACE1, 0xB400), (0xDEADBEEFCAFEBABE, 0)],
    "xorshift": [(1, 0), (88172645463325252, 0), (0xDEADBEEFCAFEBABE, 0)],
}


def u32(v):
    return "0x%08XUL" % v


def u64(v):
    return "ECO_U64(0x%08XUL, 0x%08XUL)" % (v >> 32, v & 0xFFFFFFFF)


def emit(algo):
    has_mask = 0 if algo == "xorshift" else 1
    out = ["/* Generated by reference/gen_vectors.py from reference.py - do not edit. */",
           "#define PRNG_HAS_MASK %d" % has_mask, ""]
    out.append("static const PRNGCase32 g_Cases32[] = {")
    for seed, mask in CASES32[algo]:
        seq = sequence(algo, seed, mask, 32, STEPS)
        out.append("    { %s, %s, { %s } }," % (u32(seed), u32(mask), ", ".join(u32(v) for v in seq)))
    out.append("};")
    out.append("#define PRNG_CASES32 (sizeof(g_Cases32) / sizeof(g_Cases32[0]))")
    out.append("")
    out.append("static const PRNGCase64 g_Cases64[] = {")
    for seed, mask in CASES64[algo]:
        seq = sequence(algo, seed, mask, 64, STEPS)
        out.append("    { %s, %s, { %s } }," % (u64(seed), u64(mask), ", ".join(u64(v) for v in seq)))
    out.append("};")
    out.append("#define PRNG_CASES64 (sizeof(g_Cases64) / sizeof(g_Cases64[0]))")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(emit(sys.argv[1]))
