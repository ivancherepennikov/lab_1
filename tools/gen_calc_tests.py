"""Installs the unit tests into the calculator projects A-E: gen_calc_tests.py <repo root>"""
import os, re, shutil, sys

ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
HERE = os.path.dirname(os.path.abspath(__file__))
# name: (has X, has Y, aggregatable, Subtraction(32767,-1), Subtraction(-32768,1), Division(1,0))
SPEC = {
    "CalcA": (1, 0, 0, 32767, -32768, 0),
    "CalcB": (1, 0, 1, -32768, 32767, 0),
    "CalcC": (1, 1, 0, 0, 0, -1),
    "CalcD": (0, 1, 0, 0, 0, 0),
    "CalcE": (0, 1, 1, 0, 0, 32767),
}
MAIN = r'''/*
 * <character encoding>
 *   Cyrillic (UTF-8 with signature) - Codepage 65001
 * </character encoding>
 *
 * <summary>
 *   Eco@N@ unit test client
 * </summary>
 *
 * <description>
 *   Console test client of the component: prints PASS and the number of checks or the index of
 *   the first failed check. The test client uses libc output; the component does not.
 * </description>
 *
 * <author>
 *   Copyright (c) 2026 . All rights reserved.
 * </author>
 *
 */

#include <stdio.h>
#include "IEcoSystem1.h"
#include "IdEcoInterfaceBus1.h"
#include "IdEco@N@.h"
#include "CalcTests.h"

int16_t EcoMain(IEcoUnknown* pIUnk) {
    int16_t result = -1;
    IEcoSystem1* pISys = 0;
    IEcoInterfaceBus1* pIBus = 0;

    result = pIUnk->pVTbl->QueryInterface(pIUnk, &GID_IEcoSystem, (void **)&pISys);
    if (result != 0 || pISys == 0) {
        goto Release;
    }
    result = pISys->pVTbl->QueryInterface(pISys, &IID_IEcoInterfaceBus1, (void **)&pIBus);
    if (result != 0 || pIBus == 0) {
        goto Release;
    }
#ifdef ECO_LIB
    result = pIBus->pVTbl->RegisterComponent(pIBus, &CID_Eco@N@, (IEcoUnknown*)GetIEcoComponentFactoryPtr_@CIDHEX@);
    if (result != 0) {
        printf("FAIL: RegisterComponent, result=%d\n", (int)result);
        goto Release;
    }
#endif
    result = CalcTestAll(pIBus, pIUnk);
    if (result != 0) {
        printf("FAIL: check #%d\n", (int)result);
        result = 1;
    } else {
        printf("PASS: all %lu checks passed (request with an outer unknown: result %d)\n", g_CalcChecks, (int)g_CalcAggResult);
    }

Release:
    if (pIBus != 0) {
        pIBus->pVTbl->Release(pIBus);
    }
    if (pISys != 0) {
        pISys->pVTbl->Release(pISys);
    }
    return result;
}
'''


def w(path, text):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        f.write(text.replace("\r\n", "\n").replace("\n", "\r\n"))


for name, (hx, hy, aggr, op, om, dz) in SPEC.items():
    pdir = os.path.join(ROOT, "Eco." + name)
    idh = open(os.path.join(pdir, "SharedFiles", "IdEco%s.h" % name), encoding="utf-8-sig").read()
    cid = re.search(r"GetIEcoComponentFactoryPtr_([0-9A-F]{32});", idh).group(1)
    hdr = os.path.join(pdir, "UnitTestFiles", "HeaderFiles")
    os.makedirs(hdr, exist_ok=True)
    shutil.copy(os.path.join(HERE, "CalcTests.h"), os.path.join(hdr, "CalcTests.h"))
    w(os.path.join(hdr, "CalcConfig.h"), """/* Generated by tools/gen_calc_tests.py: description of the component under test */
#include "IdEco%s.h"
#define CALC_CID (&CID_Eco%s)
#define CALC_FACTORY GetIEcoComponentFactoryPtr_%s
#define CALC_HAS_X %d
#define CALC_HAS_Y %d
#define CALC_AGGR %d
#define CALC_SUB_OVF_PLUS (%dL)
#define CALC_SUB_OVF_MINUS (%dL)
#define CALC_DIV0 (%d)
""" % (name, name, cid, hx, hy, aggr, op, om, dz))
    main = MAIN.replace("@N@", name).replace("@CIDHEX@", cid)
    w(os.path.join(pdir, "UnitTestFiles", "SourceFiles", "Eco%s.c" % name), main)
    print("tests installed:", name)
