"""Installs the unit tests into the outer projects: gen_outer_tests.py <repo root>"""
import os, re, shutil, sys

ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = {
    "Lab1Outer": dict(own_type="IEcoLab1Outer", lab2=0,
                      reg=["CalcA", "CalcB", "CalcC", "CalcD", "CalcE", "FibonacciLFSR1", "GaloisLFSR1", "Xorshift1", "Lab1Outer"]),
    "Lab2": dict(own_type="IEcoLab2", lab2=1,
                 reg=["CalcA", "CalcB", "CalcC", "CalcD", "CalcE", "FibonacciLFSR1", "GaloisLFSR1", "Xorshift1", "Lab1Outer", "Lab2"]),
}


def rd(p):
    return open(p, encoding="utf-8-sig").read().replace("\r\n", "\n")


def wr(path, text):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        f.write(text.replace("\r\n", "\n").replace("\n", "\r\n"))


def cid(name):
    return re.search(r"GetIEcoComponentFactoryPtr_([0-9A-F]{32});", rd(os.path.join(ROOT, "Eco." + name, "SharedFiles", "IdEco%s.h" % name))).group(1)


for name, sp in SPEC.items():
    pdir = os.path.join(ROOT, "Eco." + name)
    hdr = os.path.join(pdir, "UnitTestFiles", "HeaderFiles")
    os.makedirs(hdr, exist_ok=True)
    shutil.copy(os.path.join(HERE, "OuterTests.h"), os.path.join(hdr, "OuterTests.h"))
    shutil.copy(os.path.join(HERE, "OuterDemo.h"), os.path.join(hdr, "OuterDemo.h"))
    own = sp["own_type"]
    cfg = "/* Generated by tools/gen_outer_tests.py: description of the component under test */\n"
    cfg += "".join('#include "IdEco%s.h"\n' % r for r in sp["reg"])
    cfg += '#include "%s.h"\n' % own
    cfg += "#define OUTER_CID (&CID_Eco%s)\n#define OUTER_OWN_TYPE %s\n#define OUTER_OWN_IID IID_%s\n#define OUTER_IS_LAB2 %d\n#define OUTER_NAME \"Eco.%s\"\n#define OUTER_NAME_IFACE \"%s\"\n" % (name, own, own, sp["lab2"], name, own)
    wr(os.path.join(hdr, "OuterConfig.h"), cfg)
    reg_decl = "".join("    g_Reg[%d].cid = &CID_Eco%s;\n    g_Reg[%d].factory = GetIEcoComponentFactoryPtr_%s;\n" % (i, r, i, cid(r)) for i, r in enumerate(sp["reg"]))
    main = r'''/*
 * <character encoding>
 *   Cyrillic (UTF-8 with signature) - Codepage 65001
 * </character encoding>
 *
 * <summary>
 *   Eco@N@ unit test client
 * </summary>
 *
 * <description>
 *   Registers the static components needed by Eco@N@ on the interface bus and runs the tests. Prints PASS and the
 *   number of checks or the index of the first failed check. The test client uses libc output; the components do not.
 * </description>
 *
 * <author>
 *   Copyright (c) 2026 . All rights reserved.
 * </author>
 *
 */

#include <stdio.h>
#include "IEcoSystem1.h"
#include "IdEcoInterfaceBus1.h"
#include "OuterTests.h"
#include "OuterDemo.h"

#define REG_COUNT @COUNT@

typedef struct RegEntry {
    const UGUID* cid;
    IEcoComponentFactory* factory;
} RegEntry;

static RegEntry g_Reg[REG_COUNT];

int16_t EcoMain(IEcoUnknown* pIUnk) {
    int16_t result = -1;
    IEcoSystem1* pISys = 0;
    IEcoInterfaceBus1* pIBus = 0;
    int i = 0;

    result = pIUnk->pVTbl->QueryInterface(pIUnk, &GID_IEcoSystem, (void **)&pISys);
    if (result != 0 || pISys == 0) {
        goto Release;
    }
    result = pISys->pVTbl->QueryInterface(pISys, &IID_IEcoInterfaceBus1, (void **)&pIBus);
    if (result != 0 || pIBus == 0) {
        goto Release;
    }
@REGDECL@
#ifdef ECO_LIB
    for (i = 0; i < REG_COUNT; i++) {
        result = pIBus->pVTbl->RegisterComponent(pIBus, g_Reg[i].cid, (IEcoUnknown*)g_Reg[i].factory);
        if (result != 0) {
            printf("FAIL: RegisterComponent #%d, result=%d\n", i, (int)result);
            goto Release;
        }
    }
#endif
    OuterDemo(pIBus);
    result = OuterTestAll(pIBus, pIUnk);
    if (result != 0) {
        printf("FAIL: check #%d\n", (int)result);
        result = 1;
    } else {
        printf("PASS: all %lu checks passed\n", g_OuterChecks);
    }

Release:
    if (pIBus != 0) {
        pIBus->pVTbl->Release(pIBus);
    }
    if (pISys != 0) {
        pISys->pVTbl->Release(pISys);
    }
    return result;
}
'''
    main = main.replace("@N@", name).replace("@COUNT@", str(len(sp["reg"]))).replace("@REGDECL@", reg_decl)
    wr(os.path.join(pdir, "UnitTestFiles", "SourceFiles", "Eco%s.c" % name), main)
    print("tests installed:", name)
